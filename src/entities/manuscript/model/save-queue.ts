/**
 * 아직 쓰지 않은 저장 하나. **어느 원고 것인지 함께 든다.**
 *
 * 타이핑이 멎기를 기다리는 동안 원고가 바뀔 수 있다. 그때 밀린 것을 그대로 밀어
 * 넣으면 **앞 원고의 글자가 지금 원고에 쏟아진다** — 사이드바에서 원고를 빠르게
 * 오갈 때 실제로 나던 일이다. 큐가 스스로 임자를 들고 있으면 밀어 넣는 쪽이
 * 그것을 헷갈릴 수 없다.
 *
 * **두 피처가 나눠 쓴다.** 계정 원고(`useManuscriptDoc`)와 체험 원고
 * (`useSoloDraft`)의 저장 규칙이 같기 때문이다 — 늦게 온 값이 이기고, 다른
 * 원고로 넘어가면 합치지 않는다. 둘이 서로를 부를 수 없으므로 `editing.ts`가
 * 그랬듯 약속을 여기(entity)에 둔다.
 *
 * 체험 원고는 한 편뿐이라 임자가 없다. 빈 문자열을 쓰면 언제나 같은 임자가 되어
 * 늘 합쳐진다 — 그쪽에 필요한 규칙이 그것이다.
 */
export interface Queued<P> {
	docId: string;
	patch: P;
}

/**
 * 밀린 저장에 하나를 얹는다.
 *
 * 같은 원고면 합치고 **늦게 온 값이 이긴다.** 제목을 고치다 본문을 고쳤으면 둘
 * 다 나가야 하고, 제목을 두 번 고쳤으면 나중 것만 나가야 한다.
 *
 * 다른 원고면 합치지 않고 갈아탄다. 앞 원고의 밀린 저장은 여기서 버려지는 것이
 * 아니라, **부르는 쪽이 원고를 바꾸기 전에 먼저 밀어 넣는다**(`flush`).
 */
export function enqueue<P extends object>(
	now: Queued<P> | null,
	docId: string,
	patch: P,
): Queued<P> {
	return {
		docId,
		patch: now && now.docId === docId ? { ...now.patch, ...patch } : patch,
	};
}
